// Next.js injects its RSC payload and Turbopack runtime as inline scripts, so a
// strict policy needs a per-request nonce. Next reads the nonce from the request
// `Content-Security-Policy` header and tags every script it emits.
export function contentSecurityPolicy(nonce: string, isDev: boolean) {
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ''}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    ...(isDev ? [] : ['upgrade-insecure-requests']),
  ].join('; ');
}

export function createNonce() {
  return crypto.randomUUID();
}
